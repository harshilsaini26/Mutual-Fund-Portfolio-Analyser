def test_the_summary_repeats_a_real_transaction_and_it_is_still_skipped(
    lines: list[str], report: ImportReport
) -> None:
    """§5.4's first trap, on the golden portfolio rather than a toy.

    A CAS summary repeats each holding's closing position. This statement's
    summary carries the last transaction of every scheme verbatim — the HDFC
    switch-out, the ICICI switch-in and the Kotak redemption — so a state
    machine that stopped skipping it would book three extra transactions and
    every position would move.

    Mutation testing is why this is asserted. The summary originally rendered
    as one line per holding, which left nothing for the skip to be tested
    against: removing the skip changed nothing and the mutant survived.
    """
    summary_at = next(i for i, ln in enumerate(lines) if ln == "Portfolio Summary")
    repeated = [ln for ln in lines[summary_at:] if DATE_LINE.match(ln)]
    assert len(repeated) == 3, "the summary must contain transaction-shaped lines"
    assert any("Switch Out" in ln for ln in repeated)

    assert len(report.txns) == 14
    assert all(
        t.txn_ref
        for t in report.txns
    )
    # Every parsed row came from above the summary.
    reparsed = import_cas(USER, lines[:summary_at], _resolve)
    assert [t.txn_id for t in reparsed.txns] == [t.txn_id for t in report.txns]


def test_the_two_printed_balances_agree_with_each_other_and_with_the_ledger(
    report: ImportReport,
) -> None:
    """A statement prints the position twice, and both must tie.

    Each transaction line carries the running balance after it; each scheme
    block ends with an explicit `Closing Unit Balance`. They are independent
    figures on the page, and the ledger replayed from the transactions is a
    third. Reconciliation only ever consulted the running balance, so the
    closing line was going unchecked — a mutant that deleted it entirely
    survived a green suite.
    """
    book = build_book(report.txns)
    for scheme_id, isin in ISINS.items():
        scoped = [t for t in report.txns if str(t.scheme_id) == scheme_id]
        folio = scoped[0].folio

        printed_closing = report.ctx.closing_balance(folio, isin)
        last_running = max(
            scoped, key=lambda t: (t.txn_date, t.txn_seq, t.txn_ref)
        ).units_balance_rep
        computed = sum(
            (
                lot.units_remaining
                for lot in book.all_lots()
                if lot.folio == folio and lot.scheme_id == SchemeId(scheme_id)
            ),
            Decimal(0),
        )
        assert printed_closing is not None
        assert printed_closing == last_running, f"{scheme_id}: page disagrees with itself"
        assert printed_closing == computed, f"{scheme_id}: ledger disagrees with the page"


def test_the_importer_reads_a_gross_or_a_net_amount_column_the_same_way(
    report: ImportReport,
) -> None:
    """Registrars differ on whether the amount column includes stamp duty.

    Nothing in the corpus says which convention a given registrar uses, so the
    importer settles it per row against `units x nav` rather than picking one.
    This renders the same statement both ways and asserts the readings agree.

    They agree, but not to the last paisa, and the reason is worth stating.
    The amount that bought the units is Rs 22,710.4873. Printed gross it
    appears as 22,711.62 and the duty is subtracted to give 22,710.48; printed
    net it appears directly as 22,710.49. Both are the same figure rounded at
    a different point, one paisa apart — the V0-16 printing loss again, not a
    misread. What must hold exactly is that every non-money field is identical
    and that the amount is always the money that bought the units.

    Found by mutation testing: rendering the netted amount instead of the
    payment changed nothing, which was correct behaviour but accidental rather
    than asserted.
    """
    gross_lines = _render(printed_gross=True)
    net_lines = _render(printed_gross=False)
    assert gross_lines != net_lines, "the two renderings must actually differ"

    a = import_cas(USER, gross_lines, _resolve)
    b = import_cas(USER, net_lines, _resolve)
    assert a.status == b.status == "ok"
    assert a.txns == report.txns, "gross is what the golden statement renders"

    for x, y in zip(a.txns, b.txns, strict=True):
        for f in Txn.__dataclass_fields__:
            if f == "amount":
                continue
            assert getattr(x, f) == getattr(y, f), f"{x.txn_ref}.{f}"

        assert x.amount is not None and y.amount is not None
        assert abs(abs(x.amount) - abs(y.amount)) <= PRINTING_LOSS * 2

        # The convention was identified in both renderings: the stored amount
        # is the consideration that actually bought or sold the units.
        if x.units and x.nav and x.txn_type != "REVERSAL":
            product = (abs(x.units) * x.nav).quantize(Decimal("0.0001"))
            for amount in (x.amount, y.amount):
                assert abs(abs(amount) - product) <= PRINTING_LOSS * 2, x.txn_ref


def _render(*, printed_gross: bool) -> list[str]:
    """Re-render the golden statement with the other amount convention."""
    import scripts.build_v0_cas as gen

    original = gen.printed_amount
    if not printed_gross:
        gen.printed_amount = lambda t: abs(t.amount or Decimal(0))
    try:
        return [
            ln
            for ln in gen.render(load_transactions(FIXTURES / "transactions.csv"))
            if not ln.lstrip().startswith(">>>")
        ]
    finally:
        gen.printed_amount = original



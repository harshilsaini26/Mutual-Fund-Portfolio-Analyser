HDFC_DIRECT = SchemeId("INF179K01UT0")
ICICI_REGULAR = SchemeId("INF109K01761")
KOTAK_DIRECT = SchemeId("INF174KA1EZ1")

#: Money on a statement is printed to 2dp; the golden fixture computes charges
#: from a rate at `MONEY_Q` (4dp). Half a paisa is the most one rounding can
#: lose, so a field derived from a rate is bounded by it — and a field derived
#: from two rounded figures by twice it. Asserting the bound, and exactly which
#: fields carry it, is the point. See DECISIONS V0-16.
PRINTING_LOSS = Decimal("0.005")

#: Every money field the golden fixture computes from a rate, named. The round
#: trip cannot reproduce any of them, and nothing else may join the list
#: without this test failing — which is what stops "a paisa here and there"
#: from becoming the explanation for a real parser bug.
RATE_DERIVED: dict[tuple[str, str], Decimal] = {
    ("T009", "stt"): PRINTING_LOSS,
    ("T009", "exit_load"): PRINTING_LOSS,
    ("T010", "stt"): PRINTING_LOSS,
    ("T011", "stamp_duty"): PRINTING_LOSS,
    # The switch-IN amount is `proceeds - stamp_duty`, and BOTH are printed at
    # 2dp, so it inherits two roundings rather than one.
    ("T011", "amount"): PRINTING_LOSS * 2,
    ("T014", "stt"): PRINTING_LOSS,
    ("T014", "exit_load"): PRINTING_LOSS,
}

#: Fields that cannot survive the round trip, and why.
#: `txn_ref` is explicitly "not persisted" (MODULE_1.md §4.3) and is
#: regenerated from folio/scheme/date; `reverses_txn_ref` points at one.
#: `txn_seq` is re-derived per (folio, scheme, date) — see the test below.
NOT_ROUND_TRIPPED = {"txn_ref", "reverses_txn_ref", "txn_seq"}


#: M0's resolver, reached the way M1 reaches everything in M0 — through the
#: interface. This was a dict lookup in a lambda until the re-key gave the
#: golden schemes their real ISINs; a stub cannot exercise §11.3's ordering,
#: and it was the last place in the V0 gate where scheme identity did not
#: trace to a source file (`PLAN.md` §4.2).

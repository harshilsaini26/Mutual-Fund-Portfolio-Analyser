def test_gate_xirr_is_solvable_and_its_npv_returns_to_zero(
    report: ImportReport, navs: dict[str, dict[date, Decimal]]
) -> None:
    """`PLAN.md` §7: XIRR must match an independent calculation to 4dp.

    The independent calculation is a human step in a spreadsheet. What is
    machine-checkable is the defining property: discounting the cashflows at
    the solved rate returns a present value of zero. Asserted on cashflows
    built from the parsed ledger, so a parser that misread an amount or a sign
    would not produce a rate that closes.
    """
    book = build_book(report.txns)
    scheme_id = "INF174KA1EZ1"
    scoped = [t for t in report.txns if str(t.scheme_id) == scheme_id]

    units = sum(
        (
            lot.units_remaining
            for lot in book.all_lots()
            if lot.scheme_id == SchemeId(scheme_id)
        ),
        Decimal(0),
    )
    nav = max(d for d in navs[scheme_id] if d <= AS_OF)
    flows = build_cashflows(scoped, "scheme", units * navs[scheme_id][nav], AS_OF)
    rate = xirr(flows)

    assert rate is not None
    assert abs(npv(flows, rate)) < Decimal("0.01")
    assert Decimal("-0.5") < rate < Decimal("2.0"), "a plausible annualised rate"



# --- the fixture defect the round trip exposed ------------------------------


def test_the_golden_switch_crosses_amcs_and_therefore_cannot_be_linked(
    report: ImportReport, golden: list[Txn]
) -> None:
    """DECISIONS V0-16. A switch is intra-AMC by definition.

    The golden fixture switches HDFC -> ICICI. That is not a switch: units in
    one fund house cannot become units in another, so what it describes is a
    redemption followed by a purchase. The CSV carried `switch_group_id=SW001`
    because a human typed it, and nothing ever checked whether the pairing was
    possible.

    §5.8 joins the legs on `folio`, which is correct — a real switch keeps the
    folio — so the round trip cannot reproduce the hand-typed link and flags
    `UNLINKED_SWITCH` instead. The flag is right and the fixture is wrong.

    Nothing downstream breaks: §5.8 calls this a warning precisely because the
    lot engine treats each leg independently. Fixing it needs a second scheme
    from one AMC with a real NAV series, which is a data request.
    """
    out_leg = next(t for t in report.txns if t.txn_type == "SWITCH_OUT")
    in_leg = next(t for t in report.txns if t.txn_type == "SWITCH_IN")
    assert out_leg.folio != in_leg.folio
    # Since the re-key these are real ISINs, so the AMC is the issuer prefix
    # rather than something parsed out of a placeholder string.
    assert out_leg.scheme_id == HDFC_DIRECT      # INF179... = HDFC
    assert in_leg.scheme_id == ICICI_REGULAR     # INF109... = ICICI Prudential
    assert str(out_leg.scheme_id)[:6] != str(in_leg.scheme_id)[:6]

    assert [f for _, f in report.flags] == ["UNLINKED_SWITCH"]
    assert out_leg.switch_group_id is None

    # The CSV asserts the link a real statement could never support.
    golden_out = next(t for t in golden if t.txn_type == "SWITCH_OUT")
    golden_in = next(t for t in golden if t.txn_type == "SWITCH_IN")
    assert golden_out.switch_group_id == golden_in.switch_group_id == "SW001"
    assert golden_out.folio != golden_in.folio


